#!/usr/bin/env python3
"""Copies catalog/failures.json into VitralKit as the catalog that comes with Vitral.

The launcher is a single file copied into every app, so the catalog goes inside the code
rather than as a resource. A test checks that both are the same: run this after editing the
catalog."""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / "catalog/failures.json").read_text(encoding="utf-8")
json.loads(source)  # must be valid JSON
if '"""#' in source:
    sys.exit("the catalog cannot contain the sequence \"\"\"#")
body = "\n".join(("    " + line) if line else "" for line in source.rstrip("\n").split("\n"))
swift = f'''// Generated by scripts/embed-catalog.py from catalog/failures.json. Do not edit by hand.

extension FailureCatalog {{
    // Regular expressions are ICU's. In this raw string a backslash is a backslash, and JSON
    // needs it doubled: `\\\\.` matches a dot.
    static let builtInJSON = #"""
{body}
    """#
}}
'''
(root / "Sources/VitralKit/Diagnosis/BuiltInCatalog.swift").write_text(swift, encoding="utf-8")
print("Sources/VitralKit/Diagnosis/BuiltInCatalog.swift updated")
